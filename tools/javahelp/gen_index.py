#!/usr/bin/env python3
"""Generate the keyword index (JavaHelp IndexView) of every Microwave Toolbox helpset.

For each `help.hs` the generator writes `index.xml` next to it (JavaHelp Index DTD 2.0) and
makes sure the helpset declares the Index view. The entries are, sorted case-insensitively:

  * every mapped page, under its `<title>` without the "Help - " prefix (a map ID whose url
    carries an `#anchor` uses its TOC label instead, because the page title is not its own);
  * every GPT operator alias whose help page this helpset maps, as "<alias> (GPT operator)"
    (the alias -> page mapping comes from gen_params.page_map);
  * in the helpset that maps `Concept_Glossary` only, every term of concepts/glossary.html,
    pointing at the glossary page. A term that is also the text of another entry gets
    " (glossary)" appended.

Every target is a map ID of the same helpset: JavaHelp creates an index item's ID with
Map.ID.create(target, <the index's own helpset>), which only resolves that helpset's
combined map, so IDs of other (merged) helpsets cannot be used.

Usage:
    python -I tools/javahelp/gen_index.py            # print entry counts per helpset
    python -I tools/javahelp/gen_index.py --show     # print every entry (helpset | text | target)
    python -I tools/javahelp/gen_index.py --write    # rewrite index.xml files and add the Index view
    python -I tools/javahelp/gen_index.py --check    # exit 1 when an index.xml or help.hs is stale
"""
from __future__ import annotations

import argparse
import html
import os
import re
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:  # `python -I` drops the script folder from sys.path
    sys.path.insert(0, str(HERE))

import gen_params  # noqa: E402

SKIP_DIRS = {"target", ".git", "node_modules", ".idea", "test_fixtures", "__pycache__"}
INDEX = "index.xml"
GLOSSARY_ID = "Concept_Glossary"
ALIAS_SUFFIX = " (GPT operator)"
GLOSSARY_SUFFIX = " (glossary)"
VIEW_LINES = (
    '<view mergetype="javax.help.SortMerge">',
    "    <name>Index</name>",
    "    <label>Index</label>",
    "    <type>javax.help.IndexView</type>",
    f"    <data>{INDEX}</data>",
    "</view>",
)
HEADER = (
    "<?xml version='1.0' encoding='UTF-8' ?>",
    "<!-- Generated by tools/javahelp/gen_index.py; do not edit. Regenerate it (write mode) after",
    "     changing page titles, map.jhm, toc.xml, operator help IDs or the glossary. -->",
    "<!DOCTYPE index",
    '        PUBLIC "-//Sun Microsystems Inc.//DTD JavaHelp Index Version 2.0//EN"',
    '        "http://java.sun.com/products/javahelp/index_2_0.dtd">',
    "",
    '<index version="2.0">',
)


@dataclass(frozen=True)
class Entry:
    text: str
    target: str
    kind: str = "page"  # page (title) | toc (TOC label) | alias | glossary


# ---------------------------------------------------------------- reading ---

def helpset_files(repo: Path) -> list[Path]:
    out = []
    for dirpath, dirnames, filenames in os.walk(repo):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        if "help.hs" in filenames:
            out.append(Path(dirpath) / "help.hs")
    return out


def _parse_xml(path: Path):
    return gen_params._parse_xml(path)


def read_map(hs_dir: Path) -> list[tuple[str, str]]:
    """(map ID, url) in map.jhm order."""
    m = hs_dir / "map.jhm"
    if not m.exists():
        return []
    return [(e.get("target"), e.get("url")) for e in _parse_xml(m).iter("mapID")
            if e.get("target") and e.get("url")]


def read_toc(hs_dir: Path) -> list[tuple[str, str]]:
    """(label, target) of every TOC item with a target, in document order."""
    t = hs_dir / "toc.xml"
    if not t.exists():
        return []
    return [(_clean(e.get("text") or ""), e.get("target")) for e in _parse_xml(t).iter("tocitem")
            if e.get("target")]


def _decode(raw: bytes) -> str:
    try:
        return raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        return raw.decode("latin-1")


def _clean(s: str) -> str:
    s = re.sub(r"<[^>]*>", "", s)
    return re.sub(r"\s+", " ", html.unescape(s)).strip()


_TITLE = re.compile(r"<title[^>]*>(.*?)</title\s*>", re.S | re.I)
_PREFIX = re.compile(r"^help\s*[-:–—]\s*", re.I)


def title_from_html(text: str) -> str:
    """The page title without a leading "Help - "; "" when absent or just "Help"."""
    m = _TITLE.search(text)
    if not m:
        return ""
    t = _PREFIX.sub("", _clean(m.group(1)))
    return "" if t.lower() in ("", "help") else t


def page_title(path: Path) -> str:
    try:
        return title_from_html(_decode(path.read_bytes()))
    except OSError:
        return ""


_TERM = re.compile(r"<p\b[^>]*>\s*<b>(.*?)</b\s*>", re.S | re.I)


def glossary_terms_from_html(text: str) -> list[str]:
    """Every `<p><b>Term.</b> ...` entry, in page order, without the trailing period."""
    out = []
    for m in _TERM.finditer(text):
        term = _clean(m.group(1)).rstrip(" .:")
        if term and term not in out:
            out.append(term)
    return out


# --------------------------------------------------------------- building ---

def _key(p: Path) -> str:
    return os.path.normcase(os.path.normpath(str(p)))


def collect(hs_dir: Path, alias_pages: dict[str, Path]) -> list[Entry]:
    """All index entries of one helpset, sorted and de-duplicated."""
    mp = read_map(hs_dir)
    ids = {mid for mid, _ in mp}
    toc = read_toc(hs_dir)
    toc_label: dict[str, str] = {}
    for label, target in toc:
        toc_label.setdefault(target, label)
    toc_order = {target: i for i, (_, target) in enumerate(toc)}

    # one canonical map ID per page: the first one the TOC uses, else the first in map.jhm
    by_file: dict[str, list[tuple[int, str]]] = {}
    entries: list[Entry] = []
    mp_dict = dict(mp)
    for pos, (mid, url) in enumerate(mp):
        path, _, anchor = url.partition("#")
        if not path.lower().endswith((".html", ".htm")):
            continue
        if anchor:
            if toc_label.get(mid):
                entries.append(Entry(toc_label[mid], mid))
            continue
        by_file.setdefault(_key(hs_dir / path), []).append((pos, mid))
    canonical: dict[str, str] = {}
    for fkey, cands in by_file.items():
        cands.sort(key=lambda c: (toc_order.get(c[1], len(toc_order)), c[0]))
        canonical[fkey] = cands[0][1]

    # TOC labels are synonyms of the page title ("Warp" next to "Warp Operator"); they also
    # replace a title that several pages share (13 Sentinel-1 operator pages are titled "Sentinel-1")
    labels: dict[str, list[str]] = {}
    for label, target in toc:
        url = mp_dict.get(target, "")
        fkey = _key(hs_dir / url.partition("#")[0]) if url and "#" not in url else None
        if label and fkey in canonical and label not in labels.setdefault(fkey, []):
            labels[fkey].append(label)
    titles = {fkey: page_title(Path(fkey)) for fkey in canonical}
    shared = {t.casefold() for t in titles.values() if t}
    shared = {t for t in shared if sum(1 for x in titles.values() if x.casefold() == t) > 1}
    for fkey, mid in canonical.items():
        title, own = titles[fkey], labels.get(fkey, [])
        if title and not (title.casefold() in shared and own):
            entries.append(Entry(title, mid))
        for label in own:
            if label.casefold() != title.casefold() or title.casefold() in shared:
                entries.append(Entry(label, mid, "toc"))

    for alias, page in alias_pages.items():
        mid = canonical.get(_key(page))
        if mid:
            entries.append(Entry(alias + ALIAS_SUFFIX, mid, "alias"))

    if GLOSSARY_ID in ids:
        url = mp_dict[GLOSSARY_ID].partition("#")[0]
        try:
            terms = glossary_terms_from_html(_decode((hs_dir / url).read_bytes()))
        except OSError:
            terms = []
        taken = {e.text.casefold() for e in entries}
        for term in terms:
            text = term + GLOSSARY_SUFFIX if term.casefold() in taken else term
            entries.append(Entry(text, GLOSSARY_ID, "glossary"))

    return sort_entries(entries)


def sort_entries(entries) -> list[Entry]:
    seen, out = set(), []
    for e in sorted(entries, key=lambda e: (e.text.casefold(), e.text, e.target)):
        if (e.text, e.target) not in seen:
            seen.add((e.text, e.target))
            out.append(e)
    return out


def _attr(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def render(entries: list[Entry], nl: str = "\r\n") -> str:
    lines = list(HEADER)
    lines += [f'    <indexitem text="{_attr(e.text)}" target="{_attr(e.target)}"/>' for e in entries]
    lines.append("</index>")
    return nl.join(lines) + nl


def _newline(text: str) -> str:
    return "\r\n" if text.count("\r\n") * 2 > text.count("\n") else "\n"


_INDEX_VIEW = re.compile(r"<type>\s*javax\.help\.IndexView\s*</type>")


def with_index_view(hs_text: str) -> str:
    """help.hs text with the Index view inserted after the TOC view (unchanged if present)."""
    if _INDEX_VIEW.search(hs_text):
        return hs_text
    nl = _newline(hs_text)
    m = re.search(r"([ \t]*)<view\b[^>]*>(?:(?!</view>).)*?javax\.help\.TOCView.*?</view>[ \t]*\r?\n",
                  hs_text, re.S)
    if m:
        indent, at = m.group(1), m.end()
    else:
        m = re.search(r"([ \t]*)</helpset>", hs_text)
        indent, at = "    ", m.start()
    block = "".join(indent + line + nl for line in VIEW_LINES)
    return hs_text[:at] + block + hs_text[at:]


def plan(repo: Path) -> dict[Path, tuple[str, list[Entry]]]:
    """help.hs -> (help.hs text it should have, index entries), for every helpset."""
    repo = Path(repo)
    aliases = gen_params.page_map(repo)
    out = {}
    for hs in helpset_files(repo):
        out[hs] = (with_index_view(_decode(hs.read_bytes())), collect(hs.parent, aliases))
    return out


def _index_text(hs: Path, entries: list[Entry]) -> str:
    return render(entries)  # always CRLF, like the rest of the help


def write(repo: Path) -> list[Path]:
    changed = []
    for hs, (hs_text, entries) in plan(repo).items():
        raw = hs.read_bytes()
        enc = "utf-8" if raw.startswith(b"\xef\xbb\xbf") or _is_utf8(raw) else "latin-1"
        if hs_text != _decode(raw):
            hs.write_bytes(hs_text.encode(enc))
            changed.append(hs)
        idx = hs.parent / INDEX
        data = _index_text(hs, entries).encode("utf-8")
        if not idx.exists() or not same_text(idx.read_bytes(), data):
            idx.write_bytes(data)
            changed.append(idx)
    return changed


def same_text(a: bytes, b: bytes) -> bool:
    """Equal apart from line endings: git stores the help with LF and a Linux checkout keeps LF, while the
    generated text is CRLF (Windows checkouts convert back to CRLF)."""
    return a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def _is_utf8(raw: bytes) -> bool:
    try:
        raw.decode("utf-8")
        return True
    except UnicodeDecodeError:
        return False


def check(repo: Path) -> list[str]:
    repo = Path(repo)
    msgs = []
    for hs, (hs_text, entries) in plan(repo).items():
        rel = hs.relative_to(repo).as_posix()
        if hs_text != _decode(hs.read_bytes()):
            msgs.append(f"{rel}: no javax.help.IndexView view (run gen_index.py --write)")
        idx = hs.parent / INDEX
        if not idx.exists():
            msgs.append(f"{idx.relative_to(repo).as_posix()}: missing (run gen_index.py --write)")
        elif not same_text(idx.read_bytes(), _index_text(hs, entries).encode("utf-8")):
            msgs.append(f"{idx.relative_to(repo).as_posix()}: stale (run gen_index.py --write)")
    return msgs


def index_targets(index_xml: Path) -> list[str]:
    """Every indexitem target of an index.xml file (for check_javahelp.py)."""
    return [e.get("target") for e in _parse_xml(index_xml).iter("indexitem") if e.get("target")]


# -------------------------------------------------------------------- cli ---

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--repo", type=Path, default=HERE.parents[1])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--show", action="store_true", help="print every entry")
    g.add_argument("--write", action="store_true", help="rewrite index.xml files and help.hs views")
    g.add_argument("--check", action="store_true", help="exit 1 when an index.xml or help.hs is stale")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")
    repo = a.repo.resolve()
    if a.check:
        msgs = check(repo)
        for m in msgs:
            print(m)
        print(f"{len(msgs)} index problem(s)")
        return 1 if msgs else 0
    if a.write:
        changed = write(repo)
        for p in changed:
            print(p.relative_to(repo).as_posix())
        print(f"{len(changed)} file(s) changed")
        return 0
    total = 0
    for hs, (_, entries) in plan(repo).items():
        rel = hs.parent.relative_to(repo).as_posix()
        if a.show:
            for e in entries:
                print(f"{rel} | {e.text} | {e.target}")
        else:
            kinds = {k: sum(e.kind == k for e in entries) for k in ("page", "toc", "alias", "glossary")}
            print(f"{rel}: {len(entries)} (titles {kinds['page']}, TOC labels {kinds['toc']}, "
                  f"aliases {kinds['alias']}, glossary {kinds['glossary']})")
        total += len(entries)
    print(f"total: {total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
